-- 1. KULLANICILAR VE PROFİLLER TABLOSU (EGA_KULLANICILAR)
CREATE TABLE EGA_KULLANICILAR (
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    AD                  VARCHAR2(100)   DEFAULT 'Öğrenci' NOT NULL,
    SOYAD               VARCHAR2(100)   DEFAULT '' NOT NULL,
    EPOSTA              VARCHAR2(255)   NOT NULL,
    PAROLA_HASH         VARCHAR2(128)   NOT NULL,
    PAROLA_TUZ          VARCHAR2(64)    NOT NULL,
    FOTO_CLOB           CLOB,
    HEDEF_PUAN          NUMBER(3)       DEFAULT 450 NOT NULL,
    HEDEF_GUNLUK_SORU   NUMBER(4)       DEFAULT 40 NOT NULL,
    AKTIF_GUN           VARCHAR2(10),
    SERI_UZUNLUK        NUMBER(5)       DEFAULT 0 NOT NULL,
    EN_UZUN_SERI        NUMBER(5)       DEFAULT 0 NOT NULL,
    KAYIT_TARIHI        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    SON_GIRIS_TARIHI    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EGA_KULLANICILAR PRIMARY KEY (KULLANICI_ID),
    CONSTRAINT UQ_EGA_KULLANICILAR_EPOSTA UNIQUE (EPOSTA),
    CONSTRAINT CK_EGA_HEDEF_PUAN CHECK (HEDEF_PUAN BETWEEN 100 AND 500),
    CONSTRAINT CK_EGA_HEDEF_GUNLUK CHECK (HEDEF_GUNLUK_SORU BETWEEN 1 AND 500)
);

CREATE INDEX IDX_EGA_KULLANICI_EPOSTA ON EGA_KULLANICILAR(LOWER(EPOSTA));

-- 2. OTURUM VE TOKEN TABLOSU (EGA_OTURUMLAR)
CREATE TABLE EGA_OTURUMLAR (
    OTURUM_TOKEN        VARCHAR2(128)   NOT NULL,
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    OLUSTURULMA_TARIHI  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    GECERLILIK_TARIHI   TIMESTAMP WITH TIME ZONE NOT NULL,
    AKTIF_MI            NUMBER(1)       DEFAULT 1 NOT NULL,
    CONSTRAINT PK_EGA_OTURUMLAR PRIMARY KEY (OTURUM_TOKEN),
    CONSTRAINT FK_EGA_OTURUM_KULLANICI FOREIGN KEY (KULLANICI_ID)
        REFERENCES EGA_KULLANICILAR(KULLANICI_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_EGA_OTURUM_KULLANICI ON EGA_OTURUMLAR(KULLANICI_ID);

-- 3. SORU BANKASI TABLOSU (EGA_SORU_HAVUZU)
CREATE TABLE EGA_SORU_HAVUZU (
    SORU_ID             VARCHAR2(120)   NOT NULL,
    DERS_KODU           VARCHAR2(30)    NOT NULL,
    KONU_ADI            VARCHAR2(200)   NOT NULL,
    ZORLUK_DERECESI     NUMBER(1)       DEFAULT 2 NOT NULL,
    SORU_METNI          CLOB            NOT NULL,
    SECENEK_A           VARCHAR2(1000)  NOT NULL,
    SECENEK_B           VARCHAR2(1000)  NOT NULL,
    SECENEK_C           VARCHAR2(1000)  NOT NULL,
    SECENEK_D           VARCHAR2(1000)  NOT NULL,
    DOGRU_SECENEK       CHAR(1)         NOT NULL,
    GORSEL_URL          VARCHAR2(500),
    SECENEK_GORSEL_URL  VARCHAR2(500),
    KAYNAK_TURU         VARCHAR2(40)    NOT NULL,
    SINAV_YILI          NUMBER(4),
    CONSTRAINT PK_EGA_SORU_HAVUZU PRIMARY KEY (SORU_ID),
    CONSTRAINT CK_EGA_DOGRU_SECENEK CHECK (DOGRU_SECENEK IN ('A', 'B', 'C', 'D'))
);

CREATE INDEX IDX_EGA_SORU_DERS_KONU ON EGA_SORU_HAVUZU(DERS_KODU, KONU_ADI);

-- 4. KULLANICI ÇÖZÜLEN SORULAR TABLOSU (EGA_COZULEN_SORULAR)
CREATE TABLE EGA_COZULEN_SORULAR (
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    SORU_ID             VARCHAR2(120)   NOT NULL,
    DOGRU_ADET          NUMBER(5)       DEFAULT 0 NOT NULL,
    YANLIS_ADET         NUMBER(5)       DEFAULT 0 NOT NULL,
    BOS_ADET            NUMBER(5)       DEFAULT 0 NOT NULL,
    SON_COZUM_UNIX      NUMBER(15)      NOT NULL,
    CONSTRAINT PK_EGA_COZULEN_SORULAR PRIMARY KEY (KULLANICI_ID, SORU_ID),
    CONSTRAINT FK_EGA_COZULEN_KULLANICI FOREIGN KEY (KULLANICI_ID)
        REFERENCES EGA_KULLANICILAR(KULLANICI_ID) ON DELETE CASCADE
);

-- 5. GÜNLÜK ÇALIŞMA İSTATİSTİĞİ TABLOSU (EGA_GUNLUK_AKTIVITE)
CREATE TABLE EGA_GUNLUK_AKTIVITE (
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    TARIH_STR           VARCHAR2(10)    NOT NULL,
    COZULEN_SORU        NUMBER(5)       DEFAULT 0 NOT NULL,
    DOGRU_SAYISI        NUMBER(5)       DEFAULT 0 NOT NULL,
    YANLIS_SAYISI       NUMBER(5)       DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EGA_GUNLUK_AKTIVITE PRIMARY KEY (KULLANICI_ID, TARIH_STR),
    CONSTRAINT FK_EGA_GUNLUK_KULLANICI FOREIGN KEY (KULLANICI_ID)
        REFERENCES EGA_KULLANICILAR(KULLANICI_ID) ON DELETE CASCADE
);

-- 6. DENEME SINAVI SONUÇLARI TABLOSU (EGA_DENEME_SONUCLARI)
CREATE TABLE EGA_DENEME_SONUCLARI (
    DENEME_SONUC_ID     VARCHAR2(80)    NOT NULL,
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    DENEME_AD           VARCHAR2(200)   NOT NULL,
    DENEME_TUR          VARCHAR2(20)    DEFAULT 'cikmis' NOT NULL,
    TOPLAM_SORU         NUMBER(4)       NOT NULL,
    DOGRU_SAYISI        NUMBER(4)       NOT NULL,
    YANLIS_SAYISI       NUMBER(4)       NOT NULL,
    BOS_SAYISI          NUMBER(4)       NOT NULL,
    NET_SAYISI          NUMBER(6,2)     NOT NULL,
    LGS_PUANI           NUMBER(6,2)     NOT NULL,
    SURE_SANIYE         NUMBER(8)       NOT NULL,
    DERSLER_JSON        CLOB            CHECK (DERSLER_JSON IS JSON),
    BASLANGIC_PARAM     VARCHAR2(500),
    COZULME_TARIHI      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EGA_DENEME_SONUCLARI PRIMARY KEY (DENEME_SONUC_ID),
    CONSTRAINT FK_EGA_DENEME_KULLANICI FOREIGN KEY (KULLANICI_ID)
        REFERENCES EGA_KULLANICILAR(KULLANICI_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_EGA_DENEME_KULLANICI ON EGA_DENEME_SONUCLARI(KULLANICI_ID, COZULME_TARIHI DESC);

-- 7. KULLANICI ROZETLERİ TABLOSU (EGA_KULLANICI_ROZETLERI)
CREATE TABLE EGA_KULLANICI_ROZETLERI (
    KULLANICI_ID        VARCHAR2(64)    NOT NULL,
    ROZET_KODU          VARCHAR2(60)    NOT NULL,
    KAZANILMA_TARIHI    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EGA_KULLANICI_ROZET PRIMARY KEY (KULLANICI_ID, ROZET_KODU),
    CONSTRAINT FK_EGA_ROZET_KULLANICI FOREIGN KEY (KULLANICI_ID)
        REFERENCES EGA_KULLANICILAR(KULLANICI_ID) ON DELETE CASCADE
);
